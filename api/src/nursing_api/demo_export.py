"""Write web/src/mocks/demo-api.ts: the API's answers for the demo cases, for the web app's mocks.

The file is generated (`make openapi`), so the screens, the API and the pipeline share one set of
demo data. Each value is built through the API's own response models, and the TypeScript constant
is typed `DemoApi`, so `tsc` checks every field of the mock data against the contract too.
"""

import json
from datetime import datetime
from decimal import Decimal
from pathlib import Path
from uuid import UUID

from nursing_core.demo import DEMO_FACILITIES, DEMO_PERSONAS, DemoCase, load_demo_cases
from nursing_core.domain.facility import FacilityProfile
from nursing_core.domain.jobs import JobStatus
from nursing_core.domain.notes import GenerationInfo, NoteStatus
from nursing_core.domain.patient import PatientSummary
from nursing_core.domain.shifts import default_shift, shift_choices
from pydantic import BaseModel, ConfigDict, Field

from nursing_api.schemas import (
    DraftJobOut,
    FacilityOut,
    NoteOut,
    PatientDetail,
    PersonaOut,
    RoughNoteOut,
    SessionOut,
)

DEMO_API_PATH = Path(__file__).resolve().parents[3] / "web" / "src" / "mocks" / "demo-api.ts"
HEADER = (
    "// Generated by `make openapi` from the demo cases in nursing_core.demo. Don't edit.\n"
    'import type { DemoApi } from "./types";\n\n'
)
FAKE_GENERATION = GenerationInfo(
    provider="fake",
    model="fake",
    prompt_version="fdar-v1",
    input_tokens=0,
    output_tokens=0,
    cost_usd=Decimal(0),
    latency_ms=0,
)


class DemoApiData(BaseModel):
    model_config = ConfigDict(serialize_by_alias=True)

    personas: list[PersonaOut]
    sessions: dict[str, SessionOut]
    facilities: dict[str, FacilityOut]
    patients: dict[str, list[PatientSummary]]
    patient_details: dict[str, PatientDetail] = Field(serialization_alias="patientDetails")
    jobs: dict[str, DraftJobOut]
    notes: dict[str, NoteOut]
    job_for_patient: dict[str, UUID] = Field(serialization_alias="jobForPatient")


def _job_id(case: DemoCase) -> UUID:
    return UUID(int=case.patient_id.int + 3)


def _note_id(case: DemoCase) -> UUID:
    return UUID(int=case.patient_id.int + 4)


def _summary(case: DemoCase) -> PatientSummary:
    return PatientSummary(
        id=case.patient_id,
        display_name=case.display_name,
        age=case.age,
        sex=case.sex,
        ward=case.ward,
        bed_label=case.bed_label,
        facility_key=case.facility_key,
    )


def build() -> DemoApiData:
    cases = load_demo_cases()
    facilities = {facility.key: facility for facility in DEMO_FACILITIES}
    # Each facility's "now" is its first case's note time, so the sessions, the patients and
    # the shift choices all name the shift the cases were written in, and the file is stable.
    now: dict[str, datetime] = {}
    for case in cases:
        now.setdefault(case.facility_key, case.rough_note.written_at)

    def facility_out(profile: FacilityProfile) -> FacilityOut:
        return FacilityOut(
            profile=profile, version=1, shift_choices=shift_choices(now[profile.key], profile)
        )

    sessions: dict[str, SessionOut] = {}
    personas: list[PersonaOut] = []
    for persona in DEMO_PERSONAS:
        facility = facilities.get(persona.facility_key or "")
        personas.append(
            PersonaOut(
                id=persona.id,
                display_name=persona.display_name,
                initials=persona.initials,
                role=persona.role,
                facility_key=persona.facility_key,
                facility_name=facility.name if facility else None,
            )
        )
        sessions[str(persona.id)] = SessionOut(
            user_id=persona.id,
            display_name=persona.display_name,
            initials=persona.initials,
            role=persona.role,
            facility_key=persona.facility_key,
            shift=default_shift(now[facility.key], facility) if facility else None,
        )

    patients: dict[str, list[PatientSummary]] = {key: [] for key in facilities}
    details: dict[str, PatientDetail] = {}
    jobs: dict[str, DraftJobOut] = {}
    notes: dict[str, NoteOut] = {}
    job_for_patient: dict[str, UUID] = {}
    for case in cases:
        summary = _summary(case)
        patients[case.facility_key].append(summary)
        facility = facilities[case.facility_key]
        details[str(case.patient_id)] = PatientDetail(
            summary=summary, shift=default_shift(now[case.facility_key], facility), notes=[]
        )
        job_for_patient[str(case.patient_id)] = _job_id(case)
        jobs[str(_job_id(case))] = DraftJobOut(
            id=_job_id(case),
            rough_note_id=case.rough_note.id,
            status=JobStatus.SUCCEEDED,
            failure=None,
            note_id=_note_id(case),
        )
        rough = case.rough_note
        notes[str(_note_id(case))] = NoteOut(
            id=_note_id(case),
            rough_note_id=rough.id,
            encounter_id=rough.encounter_id,
            status=NoteStatus.DRAFT,
            version=1,
            draft=case.expected_draft,
            checklist=case.expected_checklist,
            generation=FAKE_GENERATION,
            signature=None,
            discard=None,
            rough_note=RoughNoteOut(
                id=rough.id,
                text=rough.text,
                written_at=rough.written_at,
                shift=rough.shift,
                note_format=rough.note_format,
            ),
            patient=summary,
        )

    return DemoApiData(
        personas=personas,
        sessions=sessions,
        facilities={key: facility_out(profile) for key, profile in facilities.items()},
        patients=patients,
        patient_details=details,
        jobs=jobs,
        notes=notes,
        job_for_patient=job_for_patient,
    )


def render() -> str:
    data = build().model_dump(mode="json")
    body = json.dumps(data, indent=2, ensure_ascii=False)
    return f"{HEADER}export const demoApi: DemoApi = {body};\n"


def main() -> None:
    DEMO_API_PATH.parent.mkdir(parents=True, exist_ok=True)
    DEMO_API_PATH.write_text(render(), encoding="utf-8")


if __name__ == "__main__":
    main()
